CREATE TABLE SEDIU (
  ID_SEDIU NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  NUME VARCHAR2(150),
  DIRECTOR_GENERAL VARCHAR2(150),
  ADRESA_SEDIU_ADM VARCHAR2(250),
  AN_INFIINTARE NUMBER(4),
  PROGRAM_STANDARD VARCHAR2(100),
  TIP_GALERIE VARCHAR2(80),
  WEBSITE VARCHAR2(255)
);

CREATE TABLE ARTIST (
  ID_ARTIST NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  NUME VARCHAR2(150),
  DATA_NASTERE DATE,
  DATA_DECES DATE,
  NATIONALITATE VARCHAR2(80),
  STILURI_ABORDATE VARCHAR2(500)
);

CREATE TABLE LOCATIE (
  ID_LOCATIE NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  NUME VARCHAR2(150),
  TIP_LOCATIE VARCHAR2(80),
  SUPRAFATA_MP NUMBER(12, 2),
  TARA VARCHAR2(80),
  ADRESA VARCHAR2(250),
  TIP_SPATIU VARCHAR2(80),
  CAPACITATE_MAXIMA NUMBER
);

CREATE TABLE SPONSOR (
  ID_SPONSOR NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  NUME VARCHAR2(150),
  TIP_SPONSOR VARCHAR2(80),
  DOMENIU_ACTIVITATE VARCHAR2(150),
  TIP_SPONSORIZARE VARCHAR2(100),
  EMAIL_CONTACT VARCHAR2(255),
  TELEFON_CONTACT VARCHAR2(40)
);

CREATE TABLE PREMIU (
  ID_PREMIU NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  NUME VARCHAR2(150),
  TIP_PREMIU VARCHAR2(80),
  LOC_OBTINUT NUMBER,
  CATEGORIE VARCHAR2(100),
  CRITERIU_ACORDARE VARCHAR2(500),
  EDITIE NUMBER(4)
);

CREATE TABLE OPERA (
  ID_OPERA NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  TITLU VARCHAR2(200),
  AN_REALIZARE NUMBER(4),
  TEHNICA VARCHAR2(120),
  SUPORT VARCHAR2(120),
  INALTIME_CM NUMBER(10, 2),
  LATIME_CM NUMBER(10, 2),
  ID_ARTIST NUMBER,
  IMAGE_URL VARCHAR2(500)
);

CREATE TABLE USERS (
  ID_USER NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  USERNAME VARCHAR2(80),
  EMAIL VARCHAR2(255),
  PASSWORD_HASH VARCHAR2(255),
  ROLE VARCHAR2(20) DEFAULT 'VIEWER',
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE EXPOZITIE (
  ID_EXPOZITIE NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  NUME VARCHAR2(200),
  TEMA VARCHAR2(250),
  TITLU VARCHAR2(200),
  DATA_START DATE,
  DATA_SFARSIT DATE,
  PUBLIC_TINTA VARCHAR2(120),
  TAXA_INTRARE NUMBER(10, 2),
  ID_SEDIU NUMBER,
  ID_LOCATIE NUMBER
);

CREATE TABLE SPONSORIZARE (
  ID_SEDIU NUMBER,
  ID_SPONSOR NUMBER,
  SUMA_SPONSORIZARE NUMBER(12, 2),
  DATA_CONTRACT DATE
);

CREATE TABLE EXPOZITIE_OPERA (
  ID_EXPOZITIE NUMBER,
  ID_OPERA NUMBER,
  POZITIE_SALA VARCHAR2(80)
);

CREATE TABLE OPERA_PREMIU (
  ID_OPERA NUMBER,
  ID_PREMIU NUMBER,
  DATA_ACORDARE DATE,
  EVENIMENT VARCHAR2(200)
);
